//1. Find square/cube of a number 
#include<iostream>
using namespace std;
int main()
{
	float square;
	float cube;
	float x;
	cout<<"Enter the Number : ";
	cin>>x;
	square=x*x;
	cube=x*x*x;
	cout<<"\nSquare of a Number is =  ";
	cout<<square;
	cout<<"\ncube of a Number is = ";
	cout<<cube;
	return 0;
}

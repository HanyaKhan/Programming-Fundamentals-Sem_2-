#include<iostream>
using namespace std;
int main()
{
	int L,W,P,A; 	//Length //Perimeter //Width //Area
	cout<<"Enter the value of Length : ";
	cin>>L;
	cout<<"Enter the value of Width : ";
	cin>>W;
	A=L*W;
	cout<<"Area : "<<A<<endl;
	P=2*(L+W);
	cout<<"Perimeter : "<<P<<endl;
					
}
